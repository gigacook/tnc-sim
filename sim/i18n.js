  /* the locale table lives in settings.js (one table): which languages there are, their <html lang>, and whether
     "follow language" shows a decimal comma. Swedish first. The setting is in TNC_SETTINGS ("tnc.settings.v1");
     "tnc.lang" is the older key, still written. */
  var SETTINGS = (typeof TNC_SETTINGS !== 'undefined' && TNC_SETTINGS) ? TNC_SETTINGS : (typeof require === 'function' ? require('./settings.js') : null);
  var LOCALES = SETTINGS.LOCALES;
  var lang = 'sv', saved;
  try {
    saved = SETTINGS.get('lang') || ((typeof localStorage !== 'undefined') && localStorage.getItem(LS_KEY));
    if (LOCALES[saved]) lang = saved;
  } catch { /* storage off: the default language */ }

  function applyDom() {
    if (typeof document === 'undefined' || !document.querySelectorAll) return;
    var dict = SHELL[lang] || SHELL.en;
    var nodes = document.querySelectorAll('[data-i18n]'), i, n, key, val;
    for (i = 0; i < nodes.length; i++) {
      n = nodes[i]; key = n.getAttribute('data-i18n');
      val = dict[key] != null ? dict[key] : (SHELL.en[key] != null ? SHELL.en[key] : null);
      if (val == null) continue;
      n.textContent = val;
    }
    /* attributes: data-i18n-label -> aria-label, data-i18n-tip -> data-tip (the tooltip), data-i18n-ph -> placeholder */
    [['data-i18n-label', 'aria-label'], ['data-i18n-tip', 'data-tip'], ['data-i18n-ph', 'placeholder']].forEach(function (p) {
      var list = document.querySelectorAll('[' + p[0] + ']'), j, k, v;
      for (j = 0; j < list.length; j++) { k = list[j].getAttribute(p[0]); v = dict[k] != null ? dict[k] : SHELL.en[k]; if (v != null) list[j].setAttribute(p[1], v); }
    });
  }

  function set(l) {
    if (!LOCALES[l]) return;
    lang = l;
    api.lang = l;
    try { if (typeof localStorage !== 'undefined') localStorage.setItem(LS_KEY, l); } catch { /* storage off */ }
    if (typeof document !== 'undefined' && document.documentElement) document.documentElement.lang = LOCALES[l].html;
    applyDom();
  }

  function t(key, fallback) {
    var dict = SHELL[lang] || SHELL.en;
    if (dict[key] != null) return dict[key];
    if (SHELL.en[key] != null) return SHELL.en[key];
    return fallback !== undefined ? fallback : key;
  }

  function pattern(text) {
    var i, m, tpl;
    for (i = 0; i < PATTERNS.length; i++) {
      m = text.match(PATTERNS[i][0]); tpl = m && PATTERNS[i][1][lang];
      if (tpl) return tpl.replace(/~?\$(\d)/g, function (a, d) { var v = m[+d] == null ? '' : m[+d]; return a.charAt(0) === '~' ? ((ONOFF[lang] || {})[v] || v) : v; });
    }
    return null;
  }
  /* interpreter and control text (UPPERCASE): errors, soft keys, run states */
  function tr(text) {
    var d = TR[lang], p;
    if (typeof text !== 'string' || !d) return text;
    if (Object.hasOwn(d, text)) return d[text];
    p = pattern(text);
    return p == null ? text : p;
  }
  /* text written by scripts, keyed by its English wording; vars fills {name} places */
  function x(text, vars) {
    var d = TX[lang], s = d && Object.hasOwn(d, text) ? d[text] : text;
    if (vars) s = s.replace(/\{(\w+)\}/g, function (a, k) { return vars[k] == null ? a : String(vars[k]); });
    return s;
  }
  /* a toast: an exact entry, else a pattern, else as it is */
  function toast(text) {
    var d = TX[lang], p;
    if (typeof text !== 'string' || !TR[lang]) return text;
    if (d && Object.hasOwn(d, text)) return d[text];
    if (Object.hasOwn(TR[lang], text)) return TR[lang][text].replace(/-?\n/g, function (a) { return a.length > 1 ? '' : ' '; });
    p = pattern(text);
    return p == null ? text : p;
  }

  var api = { lang: lang, set: set, t: t, tr: tr, x: x, toast: toast, LOCALES: LOCALES,
    tables: { SHELL: SHELL, TR: TR, TX: TX, PATTERNS: PATTERNS } };

